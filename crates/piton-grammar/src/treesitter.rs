fn highlights(vocabulary: &Vocabulary) -> String {
    let framework = if vocabulary.framework.is_empty() {
        String::new()
    } else {
        format!(
            "\n; Keywords contributed by registered frameworks.\n((keyword_declaration keyword: (word) @keyword.function)\n  (#match? @keyword.function \"^({})$\"))\n",
            vocabulary.framework.join("|")
        )
    };
    format!(
        r#"; Generated by `piton grammar`.
;
; Specific patterns come first: prose is captured only inside a value, so a
; name never falls through to the catch-all.

(comment) @comment

[
  "anchor"
  "abstract"
  "extends"
  "as"
  "export"
  "from"
  "import"
  "use"
] @keyword

(anchor_declaration name: (word) @type.definition)
(keyword_declaration keyword: (word) @keyword.function)
(keyword_declaration name: (word) @type.definition)
(extends_clause name: (word) @type)
(as_clause keyword: (word) @keyword.function)

(import_item name: (word) @variable)
(import_item alias: (word) @variable)
(export_statement name: (word) @variable)
(path) @string.special.path
(import_statement "*" @punctuation.special)

(key) @property
(typed_key) @property
(builtin_type) @type.builtin
(type name: (word) @type)

; The sigil token carries its own `{{`, because the lexer needs it to beat the
; word it would otherwise be. The closing brace has to be given the same scope
; explicitly, or an interpolation is bright at one end and dim at the other.
(sigil) @keyword.operator
(interpolation "}}" @keyword.operator)
(expression (identifier) @variable)
(self_reference) @variable.builtin
(constant) @constant.builtin
(number) @number
(string) @string
(url) @string.special.url
(escape) @string.escape
(operator) @operator

(list_item "-" @punctuation.special)
(spread_item ["+" "++"] @operator)

[":" "::" ","] @punctuation.delimiter
["[" "]" "(" ")"] @punctuation.bracket

; Prose, last so that nothing more specific is overwritten.
(value (word) @string)
(element (word) @string)
{framework}"#
    )
}

fn injections() -> String {
    "; Generated by `piton grammar`.\n; Piton prose is plain text; nothing is injected by default.\n"
        .to_string()
}

fn folds() -> String {
    r#"; Generated by `piton grammar`.
;
; The grammar is line-oriented, so the only structural fold it can offer is a
; wrapped import list. Block folding comes from `piton lsp`, which uses the
; compiler's own indentation-aware tree.
(import_list) @fold
"#
    .to_string()
}

fn indents() -> String {
    r#"; Generated by `piton grammar`.
;
; A line ending in `:` opens a block; editors that prefer regex indent rules
; find the same thing in the language configuration.
((property) @indent
  (#match? @indent ":$"))

((anchor_declaration) @indent)
((keyword_declaration) @indent)
"#
    .to_string()
}

fn outline() -> String {
    r#"; Generated by `piton grammar`.
(anchor_declaration
  ["export" "abstract" "anchor"]* @context
  name: (word) @name) @item

(keyword_declaration
  keyword: (word) @context
  name: (word) @name) @item

(property key: (key) @name) @item
(property key: (typed_key) @name) @item
"#
    .to_string()
}

fn brackets() -> String {
    r#"; Generated by `piton grammar`.
("[" @open "]" @close)
("(" @open ")" @close)
(interpolation (sigil) @open "}" @close)
"#
    .to_string()
}

/// A `tree-sitter test` corpus covering the constructs that are easy to break.
fn corpus() -> String {
    r#"================
Declarations
================

export abstract anchor Shape as shape:
    description:: string

shape Concrete extends Shape:
    description: A concrete shape

---

(source_file
  (anchor_declaration name: (word) (as_clause keyword: (word)))
  (property key: (typed_key) (type name: (builtin_type)))
  (keyword_declaration
    keyword: (word)
    name: (word)
    (extends_clause name: (word)))
  (property key: (key) (value (word) (word) (word))))

================
Prose is not a declaration
================

note: see https://example.com for details, or e.g. (this) one

---

(source_file
  (property
    key: (key)
    (value (word) (url) (word) (word) (word) (word) (word) (word))))

================
Interpolation and sigils
================

message: ${name} @{Anchor} reference{Other} SeeAlso{X} !{X} {bare}

---

(source_file
  (property
    key: (key)
    (value
      (interpolation (sigil) (expression (identifier)))
      (interpolation (sigil) (expression (identifier)))
      (interpolation (sigil) (expression (identifier)))
      (interpolation (sigil) (expression (identifier)))
      (interpolation (sigil) (expression (identifier)))
      (interpolation (sigil) (expression (identifier))))))

================
Lists and spreads
================

items:
    + {super.items}
    - one

---

(source_file
  (property key: (key))
  (spread_item (value (interpolation (sigil) (expression (self_reference) (identifier)))))
  (list_item (value (word))))
"#
    .to_string()
}

