/// A `tree-sitter test` highlight corpus.
///
/// These assertions are the difference between a grammar that parses and a
/// grammar that colours correctly, and they cover the cases where Piton is
/// unlike the languages Tree-sitter usually sees: prose is a first-class
/// value, and a keyword only means something at the head of a line.
fn highlight_test() -> String {
    r#"// A highlight corpus for `tree-sitter test`.
//
// It is a real Piton program as well as a fixture, so that opening it does not
// produce a page of errors. The one thing it cannot avoid is the warning for an
// unregistered sigil, which is the behaviour the last case is demonstrating.

use @piton/config

name: a plain sentence
// <- property

abstract anchor Skill as skill:
// <- keyword
//              ^ type.definition
//                       ^ keyword.function
    prompt:: string

anchor Example:
// <- keyword
//     ^ type.definition
    name: a plain sentence
//  ^ property
//        ^ string
    count: 42
//         ^ number
    flag: true
//        ^ constant.builtin
    quoted: "text"
//          ^ string
    computed: {self.name}
//            ^ keyword.operator
//             ^ variable.builtin
//                      ^ keyword.operator
    greeting: Hello, ${name}
//            ^ string
//                   ^ keyword.operator
    referenced: SeeAlso{name}
//              ^ keyword.operator
//                          ^ keyword.operator
    url: https://example.com/a//b
//       ^ string.special.url
    hyphen: a well-known thing
//          ^ string

skill BuildIt:
// <- keyword.function
//    ^ type.definition
    prompt: build the thing

from @piton/config import PitonConfig
// <- keyword
//   ^ string.special.path
//                        ^ variable
"#
    .to_string()
}

fn readme(source: &GrammarSource) -> String {
    format!(
        r#"# tree-sitter-piton

Generated by `piton grammar`. Build it with:

```sh
npm install
npx tree-sitter generate
npx tree-sitter parse ../../examples/*.pi
```

The grammar is deliberately line-oriented. Piton is indentation-structured, and
tracking `INDENT`/`DEDENT` in Tree-sitter needs an external scanner; every
consumer of this grammar wants it for highlighting, folding, and indent
heuristics, all of which work per line. Structural questions — resolution,
inheritance, diagnostics — are answered by `piton lsp`, which uses the real
compiler grammar.

## Where this comes from

This directory is generated from the Piton compiler and published as its own
repository at `{remote}`, because Zed, Helix, and nvim-treesitter all fetch
grammars over git. The Piton repository is the source of truth; run
`cargo xtask publish-grammar` there rather than committing here.

`src/` holds the output of `tree-sitter generate` and is committed on purpose:
the editors that consume this grammar compile `src/parser.c`, they do not run
the Tree-sitter CLI.
"#,
        remote = source.repository
    )
}
