// ---- Sublime Text -----------------------------------------------------------

fn sublime_syntax(vocabulary: &Vocabulary) -> String {
    let declaration = Vocabulary::alternation(&vocabulary.declaration);
    let self_words = Vocabulary::alternation(&vocabulary.self_words);
    let literals = Vocabulary::alternation(&vocabulary.literals);
    let types = Vocabulary::alternation(&vocabulary.types);
    format!(
        r#"%YAML 1.2
---
# Generated by `piton grammar`.
name: Piton
file_extensions: [pi]
scope: source.piton

contexts:
  main:
    - include: comment
    - include: declaration
    - include: key
    - include: value

  comment:
    - match: '(?:^|(?<=\s))//.*$'
      scope: comment.line.double-slash.piton

  declaration:
    - match: '^\s*(?:({declaration})\s+)*(anchor)\s+([A-Za-z_][\w-]*)'
      captures:
        1: keyword.control.piton
        2: keyword.control.piton
        3: entity.name.type.piton
    - match: '\b({declaration})\b'
      scope: keyword.control.piton

  key:
    - match: '^\s*([\w][\w-]*)(?=\s*(?:::|:)(?:\s|$))'
      scope: entity.name.tag.piton
    - match: '(::)\s*(?:(extends)\s+)?\b({types}|[A-Za-z_][\w-]*)\b'
      captures:
        1: keyword.operator.piton
        2: keyword.control.piton
        3: support.type.piton
    - match: '^\s*(-)(?=\s)'
      scope: punctuation.definition.list.piton
    - match: '^\s*(\+\+?)(?=\s)'
      scope: keyword.operator.piton

  value:
    - match: '([^\s{{}}\[\](),"]*)(\{{)'
      captures:
        1: keyword.other.sigil.piton
        2: punctuation.section.embedded.begin.piton
      push: interpolation
    - match: '"'
      scope: punctuation.definition.string.begin.piton
      push: string
    - match: '\b\d[\d_]*(?:\.\d[\d_]*)?\b'
      scope: constant.numeric.piton
    - match: '\b({literals})\b'
      scope: constant.language.piton

  interpolation:
    - meta_scope: meta.embedded.piton
    - match: '\}}'
      scope: punctuation.section.embedded.end.piton
      pop: true
    - match: '\b({self_words})\b'
      scope: variable.language.piton
    - match: '\b({literals})\b'
      scope: constant.language.piton
    - match: '\b\d[\d_]*(?:\.\d[\d_]*)?\b'
      scope: constant.numeric.piton
    - match: '(\+\+|&&|\|\||==|!=|>=|<=|[-+*/%<>?:.])'
      scope: keyword.operator.piton
    - match: '\b[A-Za-z_][\w-]*\b'
      scope: variable.other.piton

  string:
    - meta_scope: string.quoted.double.piton
    - match: '\\.'
      scope: constant.character.escape.piton
    - match: '"'
      pop: true
"#
    )
}

