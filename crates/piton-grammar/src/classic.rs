fn kate_syntax(vocabulary: &Vocabulary) -> String {
    let item = |words: &[String]| {
        words.iter().map(|word| format!("      <item>{word}</item>")).collect::<Vec<_>>().join("\n")
    };
    format!(
        r##"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE language SYSTEM "language.dtd">
<!-- Generated by `piton grammar`. -->
<language name="Piton" version="1" kateversion="5.0" section="Configuration"
          extensions="*.pi" mimetype="text/x-piton" indenter="normal">
  <highlighting>
    <list name="keywords">
{declaration}
    </list>
    <list name="selfwords">
{self_words}
    </list>
    <list name="constants">
{literals}
    </list>
    <list name="types">
{types}
    </list>
    <contexts>
      <context name="Normal" attribute="Normal Text" lineEndContext="#stay">
        <Detect2Chars char="/" char1="/" attribute="Comment" context="Comment"/>
        <keyword String="keywords" attribute="Keyword"/>
        <keyword String="selfwords" attribute="Builtin"/>
        <keyword String="constants" attribute="Constant"/>
        <keyword String="types" attribute="Data Type"/>
        <RegExpr String="^\s*[A-Za-z_][A-Za-z0-9_-]*(?=\s*(::|:)(\s|$))" attribute="Property"/>
        <RegExpr String="[^\s{{}}\[\](),&quot;]*\{{" attribute="Sigil" context="Interpolation"/>
        <DetectChar char="&quot;" attribute="String" context="String"/>
        <RegExpr String="\b\d[\d_]*(\.\d[\d_]*)?\b" attribute="Number"/>
        <RegExpr String="^\s*-(?=\s)" attribute="Operator"/>
        <RegExpr String="^\s*\+\+?(?=\s)" attribute="Operator"/>
      </context>
      <context name="Comment" attribute="Comment" lineEndContext="#pop"/>
      <context name="String" attribute="String" lineEndContext="#pop">
        <RegExpr String="\\." attribute="Escape"/>
        <DetectChar char="&quot;" attribute="String" context="#pop"/>
      </context>
      <context name="Interpolation" attribute="Builtin" lineEndContext="#pop">
        <DetectChar char="}}" attribute="Sigil" context="#pop"/>
        <keyword String="selfwords" attribute="Builtin"/>
        <keyword String="constants" attribute="Constant"/>
        <RegExpr String="\b\d[\d_]*(\.\d[\d_]*)?\b" attribute="Number"/>
      </context>
    </contexts>
    <itemDatas>
      <itemData name="Normal Text" defStyleNum="dsNormal"/>
      <itemData name="Keyword" defStyleNum="dsKeyword"/>
      <itemData name="Builtin" defStyleNum="dsBuiltIn"/>
      <itemData name="Constant" defStyleNum="dsConstant"/>
      <itemData name="Data Type" defStyleNum="dsDataType"/>
      <itemData name="Property" defStyleNum="dsAttribute"/>
      <itemData name="String" defStyleNum="dsString"/>
      <itemData name="Escape" defStyleNum="dsSpecialChar"/>
      <itemData name="Number" defStyleNum="dsDecVal"/>
      <itemData name="Comment" defStyleNum="dsComment"/>
      <itemData name="Operator" defStyleNum="dsOperator"/>
      <itemData name="Sigil" defStyleNum="dsPreprocessor"/>
    </itemDatas>
  </highlighting>
  <general>
    <comments>
      <comment name="singleLine" start="//"/>
    </comments>
    <keywords casesensitive="1" additionalDeliminator="-"/>
  </general>
</language>
"##,
        declaration = item(&vocabulary.declaration),
        self_words = item(&vocabulary.self_words),
        literals = item(&vocabulary.literals),
        types = item(&vocabulary.types),
    )
}

